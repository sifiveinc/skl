// Scalar functions

/**
 * @brief LFSR for 32 bit values.
 *
 * @param curr_val - Current value of the LFSR state for which the next value
 * should be determined.
 * @output The LFSR function applied to curr_val.
 *
 * The value 0 produces its own cycle, but all other uint32_t values lie in a
 * length 2^32-1 orbit which this function will cycle through.
 */
uint32_t lfsr32_scalar_advance(uint32_t curr_val) {

  const uint32_t num_bits = 32;
  // This block could be optimized with a parity or popcnt function.
  uint32_t bit = 0;
  bit ^= curr_val >> 0;
  bit ^= curr_val >> 2;
  bit ^= curr_val >> 6;
  bit ^= curr_val >> 7;
  bit &= 1u;

  uint32_t next_val = (curr_val >> 1) | (bit << (num_bits - 1));
  return next_val;
}

