/**
 * @brief Populate an f32 array with random values in the interval (min, max).
 *
 * @param arr - The array to populate.
 * @param len - The length of the array arr.
 * @param min - The lower bound of the desired output.
 * @param max - The upper bound of the desired output.
 */
void rand_f32(float *arr, size_t len, float min, float max) {
#ifdef __riscv_v
  lfsr_vectorized(arr, len, &min, &max, sizeof(float), lfsr_f32_kernel);
#else
  static uint32_t state = 1u;
  for (size_t i = 0; i < len; i++) {
    arr[i] = min + ((float)state / 0x1p32 * (max - min));
    state = lfsr32_scalar_advance(state);
  }
#endif
}

/**
 * @brief Compute the initial values for a 32 bit vectorized LFSR.
 *
 * @param vlmax - The target VLMAX for the LFSR implementation.
 *
 * The output values x[i] are formulated as follows for i in [0, vlmax):
 *   x[0] == 1 and x[i] = LFSR^K(x[i-1]), where K == 2^32 / vlmax
 * and exponentiation represents function composition.
 */
void compute_initial_lfsr_state(size_t vlmax) {
  uint64_t max_vals = 1ul << 32;
  size_t distance_between_values = max_vals / vlmax;
  uint32_t lfsr_val = 1u;
  uint64_t count = 0;

  printf("Initial lfsr state for vlmax = %zu:\n", vlmax);
  for (size_t i = 0; i < max_vals; i++) {
    if ((i % distance_between_values) == 0) {
      printf("%10u", lfsr_val);
      count++;
      if (count < vlmax) {
        printf(",");
      }
      printf(count % 8 == 0 ? "\n" : " ");
    }
    lfsr_val = lfsr32_scalar_advance(lfsr_val);
  }
  printf("\n");
}
